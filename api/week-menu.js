import { authOk, fail, callClaude, hasRedis, redis, overLimit } from "./_lib.js";
import { systemFor, PARTS } from "./chat.js";
import { LANGS, norm } from "./_season.js";
import { weekOf, parseMenu, menuPrompt } from "./_week.js";

// « Chef's weekly menu »: the SAME 21 dishes (Monday … Sunday × starter, main, dessert) for everybody, renewed every Sunday at 9:00 Paris time.
// - GET /api/week-menu?lang=fr  (access code like the other routes) → { week:{id,from,to,until}, items:[[name,sentence]×21] }.
//   Generated on the first request of the week (no cron needed); the first writer wins, so everybody sees the same menu.
// Only the dish names are generated here: the full recipe is generated by the chat when the user taps a dish.
// Redis: wm:<lang>:<week> = {items, at}, kept 20 days. The previous week's dishes are sent to the chef as « Not these ». No Redis → 501 (the app then shows no suggestion).

const TTL = 20 * 86400;
const key = (lang, id) => `wm2:${lang}:${id}`; // wm2: v238 first menus were written in English (no language rule): new keys regenerate them

async function read(lang, id) {
  const [s] = await redis([["GET", key(lang, id)]]);
  try { const d = s ? JSON.parse(s) : null; return d && Array.isArray(d.items) && d.items.length === 21 ? d.items : null; } catch { return null; }
}

async function generate(lang, avoid) {
  for (let attempt = 0; attempt < 2; attempt++) {
    const { text } = await callClaude({
      model: process.env.MODEL || "claude-haiku-5-5",
      max_tokens: 2200,
      system: systemFor(PARTS, { lang }),
      messages: [{ role: "user", content: menuPrompt(avoid, lang) }],
    });
    const items = parseMenu(text);
    if (items.length === 21 && new Set(items.map((x) => norm(x[0]))).size >= 19) return items;
  }
  throw Object.assign(new Error("upstream"), { code: "upstream" });
}

export async function getWeek(lang, wk = weekOf()) {
  let items = await read(lang, wk.id);
  if (!items) {
    const prev = wk.id > 0 ? await read(lang, wk.id - 1) : null;
    items = await generate(lang, prev ? prev.map((x) => x[0]) : []);
    const [ok] = await redis([["SET", key(lang, wk.id), JSON.stringify({ items, at: Date.now() }), "NX", "EX", TTL]]);
    if (ok !== "OK") items = (await read(lang, wk.id)) || items; // somebody else wrote first: everybody must see the same menu
  }
  return { week: wk, items };
}

export default async function handler(req, res) {
  if (req.method !== "GET") return fail(res, "method");
  res.setHeader("Cache-Control", "no-store");
  if (!hasRedis()) return res.status(501).json({ error: "storage" });
  if (!authOk(req, res)) return;
  const lang = String((req.query || {}).lang || "");
  if (!LANGS.includes(lang)) return res.status(400).json({ error: "messages" });
  if (await overLimit(req, "rl:wm:", 30)) return fail(res, "rate");
  try {
    return res.status(200).json(await getWeek(lang));
  } catch (e) {
    if (e && e.code) return fail(res, e.code);
    return res.status(502).json({ error: "storage" });
  }
}
