import { authOk, fail, callClaude, hasRedis, redis, overLimit } from "./_lib.js";
import { LANGS, norm } from "./_season.js";
import { weekOf, MENU_SYS, menuPromptJ, parseMenuJ } from "./_week.js";

// « Chef's weekly menu »: the SAME 21 dishes (Monday … Sunday × starter, main, dessert) for everybody, renewed every Sunday at 9:00 Paris time.
// - GET /api/week-menu?lang=fr  (access code like the other routes) → { week:{id,from,to,until}, items:[[name,sentence]×21] }.
//   Generated on the first request of the week (no cron needed); the first writer wins, so everybody sees the same menu.
// Only the dish names are generated here: the full recipe is generated by the chat when the user taps a dish.
// v248: a mix of the users' favourite recipes (best rated + most shared, item [title, sentence, sid, avg]: the app opens that shared copy
// as it is, never regenerated) and of new dishes from the chef. Dedicated short instructions + JSON answer, under a 45 s time budget.
// Redis: wm3:<lang>:<week> = {items, at}, kept 20 days. The previous week's dishes are sent to the chef as « Not these ». No Redis → 501 (the app then shows no suggestion).

const TTL = 20 * 86400;
const key = (lang, id) => `wm4:${lang}:${id}`; // wm4 (v249): reset of the week of 8 Nov 2026 (wm3: v248, wm2: menus written by the recipe instructions)

const MIN_OK = 18; // dishes needed to publish a menu; the missing ones (null) stay empty slots in the app

async function read(lang, id) {
  const [s] = await redis([["GET", key(lang, id)]]);
  try { const d = s ? JSON.parse(s) : null; return d && Array.isArray(d.items) && d.items.length === 21 && d.items.filter(Boolean).length >= MIN_OK ? d.items : null; } catch { return null; }
}

// Shared recipes known from « s:ck » (written by api/shared.js since v248). Older shares are indexed once by a SCAN (flag s:bf).
async function backfill() {
  const [done] = await redis([["GET", "s:bf"]]);
  if (done) return;
  let cur = "0", keys = [];
  for (let n = 0; n < 8 && keys.length < 400; n++) {
    const [r] = await redis([["SCAN", cur, "MATCH", "s:*", "COUNT", "500"]]);
    cur = String(r[0]); keys.push(...(r[1] || []).filter((k) => /^s:[a-z0-9-]{8,64}$/.test(k)));
    if (cur === "0") break;
  }
  for (let a = 0; a < keys.length; a += 50) {
    const part = keys.slice(a, a + 50), vals = await redis(part.map((k) => ["GET", k])), cmds = [];
    vals.forEach((v, x) => { try { const d = JSON.parse(v); if (d && d.ck && d.title) cmds.push(["HSETNX", "s:ck", d.ck, JSON.stringify({ sid: part[x].slice(2), t: d.title, l: d.lang })]); } catch {} });
    if (cmds.length) await redis(cmds);
  }
  await redis([["SET", "s:bf", "1"]]);
}

// The users' favourite recipes in this language: Bayesian average of the stars + a bonus for each share. Never blocks the menu.
export async function community(lang, max = 12) {
  try {
    await backfill();
    const [flat] = await redis([["HGETALL", "s:ck"]]);
    const all = [];
    for (let i = 0; i + 1 < (flat || []).length; i += 2) { try { const m = JSON.parse(flat[i + 1]); if (m && m.sid && m.t && (!m.l || m.l === lang)) all.push({ ck: flat[i], sid: m.sid, t: String(m.t).slice(0, 80) }); } catch {} }
    const list = all.slice(0, 300);
    if (!list.length) return [];
    const res = await redis(list.flatMap((c) => [["HGETALL", "r:" + c.ck], ["ZSCORE", "s:pop", c.ck]]));
    const seen = new Set(), out = [];
    list.forEach((c, x) => {
      const h = res[x * 2] || [], v = [];
      for (let i = 1; i < h.length; i += 2) { const n = Number(h[i]); if (n >= 1 && n <= 5) v.push(n); }
      const n = v.length, a = n ? v.reduce((p, q) => p + q, 0) / n : 0, sh = Number(res[x * 2 + 1]) || 0;
      if (!((n && a >= 4) || sh >= 2)) return; // good stars, or shared by at least 2 people
      const tk = c.t.toLowerCase();
      if (seen.has(tk)) return; seen.add(tk);
      out.push({ ...c, a: n ? a : 0, n, sh, score: (a * n + 3.5 * 2) / (n + 2) + 0.3 * Math.log2(1 + sh) });
    });
    return out.sort((p, q) => q.score - p.score).slice(0, max).map((c, i) => ({ ...c, id: "C" + (i + 1) }));
  } catch (e) { console.error("week-menu: community recipes unavailable", e && e.message); return []; }
}

// v251: 2 chef calls IN PARALLEL (the time of one call), then a third one only if both are short. The best answer is kept and its
// empty slots are filled from the other answer (same index = same day and course). Compact JSON, max 6000 tokens (cut answers are salvaged).
async function generate(lang, avoid) {
  const t0 = Date.now(), picks = await community(lang), why = [];
  const one = async (tag) => {
    const left = 50000 - (Date.now() - t0);
    if (left < 12000) { why.push(tag + " no time"); return []; }
    try {
      const { text, cut } = await callClaude({
        model: process.env.MODEL || "claude-haiku-5-5",
        max_tokens: 6000,
        timeout: left,
        system: MENU_SYS,
        messages: [{ role: "user", content: menuPromptJ(avoid, lang, picks) }],
      });
      const items = parseMenuJ(text, picks), ok = items.filter(Boolean).length;
      if (ok < 21) why.push(tag + " parse " + ok + (cut ? " cut" : "") + " « " + String(text).replace(/\s+/g, " ").slice(0, 50) + " »");
      return items;
    } catch (e) {
      why.push(tag + " api " + (e && (e.status || e.code)) + (e && e.detail ? " " + e.detail : ""));
      if (e && (e.code === "badkey" || e.code === "credit" || e.code === "nokey" || e.code === "model")) throw e;
      return [];
    }
  };
  const n = (x) => x.filter(Boolean).length;
  const merge = (list) => {
    list = list.filter((x) => x.length).sort((a, b) => n(b) - n(a));
    if (!list.length) return [];
    const out = list[0].slice(0, 21), names = new Set(out.filter(Boolean).map((x) => x[0].toLowerCase()));
    while (out.length < 21) out.push(null);
    for (const other of list.slice(1)) out.forEach((x, k) => { const y = other[k]; if (!x && y && !names.has(y[0].toLowerCase())) { out[k] = y; names.add(y[0].toLowerCase()); } });
    return out;
  };
  let best = merge(await Promise.all([one("A"), one("B")]));
  if (n(best) < 21) best = merge([best, await one("C")]);
  if (n(best) < MIN_OK) {
    console.error("week-menu: failed", why.join(" | "));
    throw Object.assign(new Error("upstream"), { code: "upstream", why: why.join(" | ") || "no attempt" });
  }
  console.log("week-menu:", lang, n(best), "dishes,", best.filter((x) => x && x[2]).length, "community of", picks.length, why.length ? "| " + why.join(" | ") : "");
  return best;
}

export async function getWeek(lang, wk = weekOf()) {
  let items = await read(lang, wk.id);
  if (!items) {
    const prev = wk.id > 0 ? await read(lang, wk.id - 1) : null;
    items = await generate(lang, prev ? prev.filter(Boolean).map((x) => x[0]) : []);
    const [ok] = await redis([["SET", key(lang, wk.id), JSON.stringify({ items, at: Date.now() }), "NX", "EX", TTL]]);
    if (ok !== "OK") items = (await read(lang, wk.id)) || items; // somebody else wrote first: everybody must see the same menu
  }
  return { week: wk, items };
}

export default async function handler(req, res) {
  if (req.method !== "GET") return fail(res, "method");
  res.setHeader("Cache-Control", "no-store");
  if (!hasRedis()) return res.status(501).json({ error: "storage" });
  if (!authOk(req, res)) return;
  const lang = String((req.query || {}).lang || "");
  if (!LANGS.includes(lang)) return res.status(400).json({ error: "messages" });
  if (await overLimit(req, "rl:wm:", 30)) return fail(res, "rate");
  try {
    return res.status(200).json(await getWeek(lang));
  } catch (e) {
    console.error("week-menu: failed", e && e.code, e && e.message, e && e.why);
    if (e && e.code) return res.status(e.code === "timeout" ? 504 : e.code === "rate" ? 429 : 502).json({ error: e.code, detail: String(e.why || e.detail || "").slice(0, 300) });
    return res.status(502).json({ error: "storage", detail: String((e && e.message) || "").slice(0, 160) });
  }
}
